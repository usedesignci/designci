/**
 * Regenerates packages/core/src/suggest/tailwind-stock-data.ts — the table of
 * stock Tailwind default-theme values the mapping suggester uses to tell a
 * team's own design decisions apart from framework defaults.
 *
 * The default theme is flattened by parseTailwindTheme itself, so the names and
 * raw values in the table are byte-for-byte what the adapter produces for a
 * user's resolved theme. Run after building core:
 *
 *   pnpm build && node scripts/generate-tailwind-stock.mjs
 */

import { writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(import.meta.url)

const resolveConfig = require('tailwindcss/resolveConfig.js')
const { version } = require('tailwindcss/package.json')
const { parseTailwindTheme, sourceId } = await import(
  path.join(root, 'packages/core/dist/index.js')
)

const theme = resolveConfig({ content: [] }).theme
const source = {
  id: sourceId('tailwind'),
  kind: 'tailwind',
  role: 'code',
  label: 'tailwind defaults',
}

const parsed = parseTailwindTheme(theme, source)
if (!parsed.ok) {
  console.error('could not parse the default theme:', parsed.diagnostics)
  process.exit(1)
}

const entries = [...parsed.value.tokens]
  .map((token) => [token.id, token.raw])
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))

const body = entries
  .map(([name, raw]) => `  ${JSON.stringify(name)}: ${JSON.stringify(raw)},`)
  .join('\n')

const file = `/**
 * Stock Tailwind default-theme values, keyed by the token name the tailwind
 * adapter produces (e.g. \`colors.blue.500\`). GENERATED by
 * scripts/generate-tailwind-stock.mjs from tailwindcss ${version} — regenerate
 * rather than hand-editing.
 *
 * Used only by the mapping suggester to rank a team's own decisions above
 * framework defaults; nothing in the check path reads this table.
 */

export const STOCK_TAILWIND_VERSION = ${JSON.stringify(version)}

export const STOCK_TAILWIND_RAW: Readonly<Record<string, string>> = {
${body}
}
`

const out = path.join(root, 'packages/core/src/suggest/tailwind-stock-data.ts')
await writeFile(out, file)
console.log(`wrote ${entries.length} stock values to ${path.relative(root, out)}`)
