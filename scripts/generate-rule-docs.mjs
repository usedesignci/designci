/**
 * Regenerates docs/rules.md from the plugin's RULE_DOCS — the same prose the
 * plugin shows in its rule-detail panel, so the docs and the in-product help
 * cannot drift apart. Run after building:
 *
 *   pnpm build && node scripts/generate-rule-docs.mjs
 */

import { writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const { RULE_DOCS } = await import(
  path.join(root, 'packages/figma-plugin/dist-tsc/rule-docs.js')
)

const TOKEN_RULES = ['token-value-mismatch', 'missing-token', 'duplicate-token']

const section = (ids, note) =>
  ids
    .map((id) => {
      const doc = RULE_DOCS[id]
      return [
        `### \`${id}\``,
        '',
        `**${doc.title}** · default severity: \`${doc.defaultSeverity}\``,
        '',
        `> ${doc.rule}`,
        '',
        `**Why it matters.** ${doc.why}`,
        '',
        `**How to fix it.** ${doc.howToFix}`,
        '',
      ].join('\n')
    })
    .join('\n')

const canvasRules = Object.keys(RULE_DOCS).filter((id) => !TOKEN_RULES.includes(id))

const page = `# Rules

<!-- GENERATED by scripts/generate-rule-docs.mjs from the plugin's RULE_DOCS.
     Edit packages/figma-plugin/src/rule-docs.ts and regenerate. -->

Every check Design CI runs, and how each finding is treated by default.
Severity is policy, not rule logic: set any rule to \`off\`, \`info\`, \`warn\`
or \`error\` in [\`designci.config.json\`](./configuration.md#rules) and every
surface — CLI, Action, Figma plugin — follows it.

## Token rules

These compare sources — the Figma snapshot against your code tokens — and run
everywhere: \`designci check\`, the GitHub Action, and the plugin.

${section(TOKEN_RULES)}
## Canvas rules

These lint the current page inside the Figma plugin: they judge **binding
state and value equality only** — never name similarity. Canvas findings are a
designer's pre-flight and deliberately never enter the health score, which
belongs to the token comparison CI runs.

${section(canvasRules)}
---

*This page is generated from the plugin's own rule documentation
(\`packages/figma-plugin/src/rule-docs.ts\`), so what you read here is what
the plugin shows in its Rules tab.*
`

const out = path.join(root, 'docs/rules.md')
await writeFile(out, page)
console.log(`wrote ${Object.keys(RULE_DOCS).length} rules to ${path.relative(root, out)}`)
